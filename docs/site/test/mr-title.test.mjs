// The merge request title check (scripts/docs-mr-title.mjs): a releasing title is what the public Changelog shows.
// Run: npm test (in docs/site).
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { test } from 'node:test';
import { parseTitle, titleProblems } from '../../../scripts/docs-mr-title.mjs';

const script = new URL('../../../scripts/docs-mr-title.mjs', import.meta.url).pathname;
const run = (title) => {
  try {
    return { code: 0, out: execFileSync('node', [script, title], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }) };
  } catch (e) {
    return { code: e.status, out: `${e.stdout}${e.stderr}` };
  }
};

test('the conventional-commit prefix is stripped before the check', () => {
  assert.deepEqual(parseTitle('feat(typescript)!: createDocument takes a folder'), { type: 'feat', scope: 'typescript', breaking: true, subject: 'createDocument takes a folder' });
  assert.deepEqual(titleProblems('fix(retry): the retry budget refills after a minute'), []);
});

test('a passing title exits 0', () => {
  const r = run('feat(python)!: list_documents pages by cursor');
  assert.equal(r.code, 0, r.out);
});

test('a failing title exits 1 and names the rule it broke', () => {
  const r = run('fix: the conformance suite covers stream.reset');
  assert.equal(r.code, 1);
  assert.match(r.out, /the title mentions the conformance suites/);
  assert.match(run('feat(codegen): nested clients').out, /the scope mentions the generators/);
  assert.match(run('Draft: fix: generated by the generators').out, /the title mentions the generators/);
  assert.match(run('fix!: the Developer tools area can switch off document access control').out, /internal-only area or tool/);
});

test('a title that never reaches the Changelog is not checked', () => {
  for (const title of ['chore(conformance): new cases', 'docs: the generators README', 'ci: run conformance nightly', 'Draft: anything']) assert.equal(run(title).code, 0, title);
});
