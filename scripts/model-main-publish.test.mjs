// Tests for scripts/model-main-publish.sh, model:main's commit, tag and push, against a local bare repository standing
// in for GitLab. The CI job release:scripts runs it:
//   node --test scripts/model-main-publish.test.mjs
// Each test copies the files the script reads (it, scripts/version.mjs and every file that names the version) into a
// fresh repository, pushes that to a bare one as main, clones it as the job's checkout, and stamps a beta there, as
// model:main does before it publishes.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
// A version VERSION can never already name (the next major's first beta), so the stamp changes every stamped file
// whatever version main is at
const VERSION = `${Number(fs.readFileSync(path.join(root, 'VERSION'), 'utf8').trim().split('.')[0]) + 1}.0.0-beta.1`;
const stamped = execFileSync('node', [path.join(root, 'scripts/version.mjs'), 'files'], { encoding: 'utf8' }).trim().split('\n');

// Git with no user or system configuration (no signing, hooks or default branch from the machine running the test)
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'model-main-publish-'));
const gitconfig = path.join(tmp, 'gitconfig');
fs.writeFileSync(gitconfig, '[user]\n\tname = test\n\temail = test@example.com\n[init]\n\tdefaultBranch = main\n');
const env = { ...process.env, GIT_CONFIG_GLOBAL: gitconfig, GIT_CONFIG_NOSYSTEM: '1', APP_COMMIT: 'e2b58500d962aaaaaaaa', CI_PIPELINE_ID: '1' };
const git = (cwd, ...args) => execFileSync('git', args, { cwd, env, encoding: 'utf8' }).trim();

/** { bare, job, base }: main in `bare`, and `job`, a clone of it with the beta stamped and the model changed. */
function setup(name) {
  const dir = path.join(tmp, name);
  const seed = path.join(dir, 'seed');
  for (const file of ['scripts/version.mjs', 'scripts/model-main-publish.sh', 'model/model.lock.json', 'README.md', ...stamped]) {
    fs.mkdirSync(path.dirname(path.join(seed, file)), { recursive: true });
    fs.copyFileSync(path.join(root, file), path.join(seed, file));
  }
  // A stand-in for the generated conformance cases, which the script stages as a directory
  fs.mkdirSync(path.join(seed, 'conformance/cases'), { recursive: true });
  fs.writeFileSync(path.join(seed, 'conformance/cases/examples.json'), '[]\n');
  git(seed, 'init', '-q');
  git(seed, 'add', '-A');
  git(seed, 'commit', '-q', '-m', 'main');
  const bare = path.join(dir, 'bare.git');
  git(dir, 'init', '-q', '--bare', bare);
  git(seed, 'push', '-q', bare, 'HEAD:refs/heads/main');
  const job = path.join(dir, 'job');
  git(dir, 'clone', '-q', bare, job);
  const base = git(job, 'rev-parse', 'HEAD');
  // What model:main changes before it publishes: the model, the generated code and the version in every stamped file
  fs.appendFileSync(path.join(job, 'model/model.lock.json'), '\n');
  fs.writeFileSync(path.join(job, 'go/new_operation.go'), '// Code generated by smithy-go-codegen DO NOT EDIT.\npackage caitlyn\n');
  execFileSync('node', ['scripts/version.mjs', 'release', VERSION], { cwd: job, env, stdio: 'pipe' });
  return { dir, bare, job, base };
}

const publish = ({ job, base, bare }) =>
  spawnSync('bash', ['scripts/model-main-publish.sh', VERSION, base, bare, 'main'], { cwd: job, env, encoding: 'utf8' });
const refs = (bare) => git(bare, 'for-each-ref', '--format=%(refname) %(objectname)');
const hasTag = (bare) => refs(bare).includes(`refs/tags/v${VERSION}`);

test('pushes main and the beta tag on one commit, and that commit carries the version in every stamped file', () => {
  const r = setup('happy');
  const run = publish(r);
  assert.equal(run.status, 0, run.stderr);
  const main = git(r.bare, 'rev-parse', 'refs/heads/main');
  assert.equal(git(r.bare, 'rev-parse', `refs/tags/v${VERSION}^{commit}`), main);
  assert.equal(git(r.bare, 'rev-parse', 'refs/heads/main^'), r.base);
  // The tag's tree, checked as release:version checks it on the tag pipeline
  const tree = path.join(r.dir, 'tag-tree');
  fs.mkdirSync(tree);
  execFileSync('sh', ['-c', `git -C "${r.bare}" archive "v${VERSION}" | tar -x -C "${tree}"`], { env });
  const check = spawnSync('node', ['scripts/version.mjs', 'check', VERSION], { cwd: tree, encoding: 'utf8' });
  assert.equal(check.status, 0, check.stderr);
  for (const file of ['conformance/rust/Cargo.lock', 'examples/rust/Cargo.lock', 'cli/internal/spec/commands.json', 'go/new_operation.go']) {
    assert.ok(git(r.bare, 'show', '--name-only', '--format=', 'refs/heads/main').split('\n').includes(file), `${file} is not committed`);
  }
});

test('when main has moved since the job started, it pushes nothing: no commit and no tag', () => {
  const r = setup('moved');
  // !115 merging while the suites run
  const other = path.join(r.dir, 'other');
  git(r.dir, 'clone', '-q', r.bare, other);
  fs.appendFileSync(path.join(other, 'README.md'), '\nmerged meanwhile\n');
  git(other, 'commit', '-q', '-am', 'docs: merged meanwhile');
  git(other, 'push', '-q', 'origin', 'HEAD:main');
  const moved = git(r.bare, 'rev-parse', 'refs/heads/main');
  const run = publish(r);
  assert.notEqual(run.status, 0);
  assert.match(run.stderr, /main moved while this job ran/);
  assert.match(run.stderr, /Retry this job/);
  assert.equal(git(r.bare, 'rev-parse', 'refs/heads/main'), moved);
  assert.ok(!hasTag(r.bare), refs(r.bare));
});

test('when the server refuses main after the check, the atomic push refuses the tag too', () => {
  const r = setup('refused');
  // main moving between the check and the push looks to the push like this: the server refuses the main update
  const hook = path.join(r.bare, 'hooks/update');
  fs.writeFileSync(hook, '#!/bin/sh\n[ "$1" = refs/heads/main ] && { echo "main moved" >&2; exit 1; }\nexit 0\n', { mode: 0o755 });
  const run = publish(r);
  assert.notEqual(run.status, 0);
  assert.ok(run.stderr.includes(`neither main nor v${VERSION} changed`), run.stderr);
  assert.equal(git(r.bare, 'rev-parse', 'refs/heads/main'), r.base);
  assert.ok(!hasTag(r.bare), refs(r.bare));
  // The first model:main run's push, without --atomic: the tag lands and main is refused, as in job 1164684
  const plain = spawnSync('git', ['push', '-q', r.bare, 'HEAD:refs/heads/main', `refs/tags/v${VERSION}`], { cwd: r.job, env, encoding: 'utf8' });
  assert.notEqual(plain.status, 0);
  assert.ok(hasTag(r.bare), 'a plain push was expected to leave the tag behind');
});

test('a tracked file the job changed but does not commit stops it before anything is committed or pushed', () => {
  const r = setup('stray');
  fs.appendFileSync(path.join(r.job, 'README.md'), '\nchanged by a test suite\n');
  const run = publish(r);
  assert.notEqual(run.status, 0);
  assert.match(run.stderr, /README\.md/);
  assert.equal(git(r.job, 'rev-parse', 'HEAD'), r.base);
  assert.equal(git(r.bare, 'rev-parse', 'refs/heads/main'), r.base);
  assert.ok(!hasTag(r.bare), refs(r.bare));
});

test.after(() => fs.rmSync(tmp, { recursive: true, force: true }));
