// Writes conformance/cases/examples.json: one conformance case per @examples entry in the model
// (PROTOCOL.md section 11, design guide section 14), plus a 403 case per operation (see below).
// Each case holds the example's input, the HTTP request an SDK must send for it (worked out from
// the model's HTTP bindings), and the response the mock server answers with. The harnesses call the
// operation with the input; the mock server checks the request and serves the response.
//
// 403: no operation's @examples has a 403, because PermissionDeniedError is a service error that
// @permission produces before any record is read. Every operation can return it, so each gets a
// synthesised 403 case (marked "synthesised") using its first example's input.
//
// Usage: node scripts/gen-example-cases.mjs   (reads build/model/model.json; run prepare-model first)
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const ast = JSON.parse(fs.readFileSync(path.join(root, 'build/model/model.json'), 'utf8'));
const shapes = ast.shapes;
const SERVICE = 'ai.caitlyn.v3#Caitlyn';
const T = (s) => `smithy.api#${s}`;
const service = shapes[SERVICE];

const members = (id) => {
  const s = shapes[id];
  let out = {};
  for (const { target } of s.mixins ?? []) out = { ...out, ...members(target) };
  return { ...out, ...(s.members ?? {}) };
};

const operations = new Set();
const visit = (shape) => {
  for (const { target } of shape.operations ?? []) operations.add(target);
  for (const { target } of shape.collectionOperations ?? []) operations.add(target);
  for (const key of ['create', 'put', 'read', 'update', 'delete', 'list']) if (shape[key]) operations.add(shape[key].target);
  for (const { target } of shape.resources ?? []) visit(shapes[target]);
};
visit(service);

const timestampOf = (memberDef) => shapes[memberDef.target]?.type === 'timestamp';
const queryValue = (v) => (typeof v === 'boolean' || typeof v === 'number' ? String(v) : v);

function request(opId, input) {
  const op = shapes[opId];
  const http = op.traits[T('http')];
  const req = { method: http.method, path: http.uri.split('?')[0], query: {}, headers: {} };
  let body;
  let hasBodyMembers = false;
  for (const [name, def] of Object.entries(members(op.input.target))) {
    const t = def.traits ?? {};
    const v = input[name];
    if (t[T('httpLabel')] !== undefined) {
      req.path = req.path.replace(`{${name}}`, encodeURIComponent(v));
    } else if (t[T('httpQuery')] !== undefined) {
      if (v !== undefined) req.query[t[T('httpQuery')]] = Array.isArray(v) ? v.map(queryValue) : queryValue(v);
    } else if (t[T('httpHeader')] !== undefined) {
      const header = t[T('httpHeader')].toLowerCase();
      // An unset idempotency token is generated by the SDK: any value will do.
      if (v !== undefined) req.headers[header] = String(v);
      else if (t[T('idempotencyToken')] !== undefined) req.headers[header] = '*';
    } else if (t[T('httpPayload')] !== undefined) {
      throw new Error(`${opId}: @httpPayload inputs are not supported by the example cases yet`);
    } else {
      hasBodyMembers = true;
      if (v !== undefined) (body ??= {})[t[T('jsonName')] ?? name] = v;
    }
  }
  if (hasBodyMembers) req.body = body ?? {};
  return req;
}

function successResponse(opId, output = {}) {
  const op = shapes[opId];
  const http = op.traits[T('http')];
  if (op.traits['ai.caitlyn.traits#sseEvents']) return { status: http.code ?? 200, stream: true };
  const headers = {};
  let body = {};
  for (const [name, def] of Object.entries(members(op.output.target))) {
    const t = def.traits ?? {};
    if (output[name] === undefined) continue;
    if (t[T('httpHeader')] !== undefined) headers[t[T('httpHeader')]] = String(output[name]);
    else if (t[T('httpPayload')] !== undefined) throw new Error(`${opId}: @httpPayload outputs are not supported by the example cases yet`);
    else body[t[T('jsonName')] ?? name] = output[name];
  }
  return { status: http.code ?? 200, headers, body };
}

function errorResponse(shapeId, content) {
  const status = shapes[shapeId].traits[T('httpError')];
  return { status, shape: shapeId.split('#')[1], code: content.code, requestId: content.requestId, body: content };
}

const cases = [];
for (const opId of [...operations].sort()) {
  const op = shapes[opId];
  const name = opId.split('#')[1];
  const examples = op.traits[T('examples')] ?? [];
  for (const ex of examples) {
    cases.push({
      id: `${name}: ${ex.title}`,
      operation: name,
      input: ex.input ?? {},
      request: request(opId, ex.input ?? {}),
      response: ex.error ? errorResponse(ex.error.shapeId, ex.error.content) : successResponse(opId, ex.output),
      expected: ex.error ? { error: { status: shapes[ex.error.shapeId].traits[T('httpError')], code: ex.error.content.code, shape: ex.error.shapeId.split('#')[1], requestId: ex.error.content.requestId } } : { output: ex.output ?? null },
    });
  }
  const errors = [...(op.errors ?? []), ...(service.errors ?? [])].map((e) => e.target);
  const forbidden = errors.find((e) => shapes[e].traits[T('httpError')] === 403);
  if (forbidden && examples.length) {
    const content = {
      type: 'https://build.caitlyn.ai/errors/PERMISSION_DENIED',
      title: 'Permission denied',
      status: 403,
      code: 'PERMISSION_DENIED',
      detail: `The caller may not call ${name}.`,
      requestId: '01JC9Q2W7R4M0H2T6N1S8V3B70',
    };
    cases.push({
      id: `${name}: permission denied (403, synthesised)`,
      operation: name,
      synthesised: true,
      input: examples[0].input ?? {},
      request: request(opId, examples[0].input ?? {}),
      response: errorResponse(forbidden, content),
      expected: { error: { status: 403, code: 'PERMISSION_DENIED', shape: forbidden.split('#')[1], requestId: content.requestId } },
    });
  }
}
const out = { generatedFrom: 'build/model/model.json', note: 'Generated by scripts/gen-example-cases.mjs. Do not edit.', cases };
fs.writeFileSync(path.join(root, 'conformance/cases/examples.json'), JSON.stringify(out, null, 2) + '\n');
const synth = cases.filter((c) => c.synthesised).length;
console.log(`gen-example-cases: ${cases.length - synth} cases from @examples and ${synth} synthesised 403 cases, for ${operations.size} operations`);
