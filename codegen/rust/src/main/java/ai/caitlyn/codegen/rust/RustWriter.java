package ai.caitlyn.codegen.rust;

import software.amazon.smithy.codegen.core.ImportContainer;
import software.amazon.smithy.codegen.core.Symbol;
import software.amazon.smithy.codegen.core.SymbolWriter;

/**
 * Writes one Rust file of the generated crate. Code is written as plain lines (no Smithy formatting
 * expressions, so Rust's own {@code $} and braces need no escaping); every file starts with the same
 * {@code use} lines, and rustfmt lays it out afterwards.
 */
final class RustWriter extends SymbolWriter<RustWriter, RustWriter.NoImports> {

    static final String HEADER = "// Code generated by caitlyn-rust-codegen from the Caitlyn Smithy model. DO NOT EDIT.\n\n";

    private final String preamble;

    RustWriter(String preamble) {
        super(new NoImports());
        this.preamble = preamble;
        trimTrailingSpaces(true);
    }

    /** Writes text as it is (one or more lines; the writer adds the final newline itself). */
    RustWriter l(String text) {
        if (text.isEmpty()) {
            return this;
        }
        writeWithNoFormatting(text.endsWith("\n") ? text.substring(0, text.length() - 1) : text);
        return this;
    }

    @Override
    public String toString() {
        return HEADER + preamble + super.toString();
    }

    static final class NoImports implements ImportContainer {
        @Override
        public void importSymbol(Symbol symbol, String alias) {}
    }
}
