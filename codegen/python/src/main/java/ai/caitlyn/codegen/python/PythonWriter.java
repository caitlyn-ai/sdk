package ai.caitlyn.codegen.python;

import java.util.Map;
import java.util.TreeMap;
import java.util.TreeSet;
import software.amazon.smithy.codegen.core.ImportContainer;
import software.amazon.smithy.codegen.core.Symbol;
import software.amazon.smithy.codegen.core.SymbolWriter;

/**
 * Writes one Python module. {@code $T} writes a symbol's name and imports it from its module
 * unless it is defined in the module being written; {@code $D} writes a docstring.
 */
final class PythonWriter extends SymbolWriter<PythonWriter, PythonWriter.Imports> {

    static final String HEADER = "# Code generated by caitlyn-python-codegen from the Caitlyn Smithy model. DO NOT EDIT.\n";

    private final String module;

    PythonWriter(String module) {
        super(new Imports(module));
        this.module = module;
        setIndentText("    ");
        trimTrailingSpaces(true);
        trimBlankLines(2);
        putFormatter('T', (value, indent) -> {
            Symbol symbol = (Symbol) value;
            if (!symbol.getNamespace().isEmpty()) {
                getImportContainer().importSymbol(symbol, symbol.getName());
            }
            return symbol.getName();
        });
        putFormatter('D', (value, indent) -> docstring(String.valueOf(value), indent));
    }

    String module() {
        return module;
    }

    /** {@code from <module> import <name>}. */
    PythonWriter importFrom(String fromModule, String name) {
        getImportContainer().add(fromModule, name);
        return this;
    }

    /** {@code import <module>}. */
    PythonWriter importModule(String name) {
        getImportContainer().addModule(name);
        return this;
    }

    /** A triple-quoted docstring. The writer indents continuation lines itself. */
    static String docstring(String text, String indent) {
        String body = text.strip().replace("\\", "\\\\").replace("\"\"\"", "\\\"\\\"\\\"");
        if (body.endsWith("\"")) {
            body = body + " ";
        }
        if (!body.contains("\n")) {
            return "\"\"\"" + body + "\"\"\"";
        }
        return "\"\"\"" + body + "\n\"\"\"";
    }

    @Override
    public String toString() {
        String body = super.toString();
        String imports = getImportContainer().toString();
        StringBuilder out = new StringBuilder(HEADER);
        if (body.startsWith("\"\"\"")) {
            // Module docstring first, then imports.
            int end = body.indexOf("\"\"\"", 3) + 3;
            out.append(body, 0, end).append("\n\n");
            body = body.substring(end).stripLeading();
        }
        out.append("from __future__ import annotations\n\n");
        if (!imports.isEmpty()) {
            out.append(imports).append("\n\n");
        }
        return out.append(body).toString();
    }

    /** Collects {@code from X import Y} lines; renders stdlib, third-party, then this package. */
    static final class Imports implements ImportContainer {
        private static final java.util.Set<String> STDLIB = java.util.Set.of(
                "collections", "collections.abc", "dataclasses", "datetime", "decimal", "enum", "os", "pathlib",
                "typing", "types", "uuid");
        private final String module;
        private final Map<String, TreeSet<String>> from = new TreeMap<>();
        private final TreeSet<String> modules = new TreeSet<>();

        Imports(String module) {
            this.module = module;
        }

        @Override
        public void importSymbol(Symbol symbol, String alias) {
            add(symbol.getNamespace(), symbol.getName());
        }

        void add(String fromModule, String name) {
            if (fromModule.isEmpty() || fromModule.equals(module) || fromModule.equals("builtins")) {
                return;
            }
            from.computeIfAbsent(fromModule, k -> new TreeSet<>()).add(name);
        }

        void addModule(String name) {
            modules.add(name);
        }

        @Override
        public String toString() {
            StringBuilder std = new StringBuilder();
            StringBuilder third = new StringBuilder();
            StringBuilder local = new StringBuilder();
            String pkg = module.contains(".") ? module.substring(0, module.indexOf('.')) : module;
            for (String m : modules) {
                (STDLIB.contains(m) ? std : third).append("import ").append(m).append('\n');
            }
            for (Map.Entry<String, TreeSet<String>> e : from.entrySet()) {
                String root = e.getKey().contains(".") ? e.getKey().substring(0, e.getKey().indexOf('.')) : e.getKey();
                StringBuilder target = STDLIB.contains(e.getKey()) || STDLIB.contains(root) ? std
                        : root.equals(pkg) ? local : third;
                String line = "from " + e.getKey() + " import " + String.join(", ", e.getValue());
                if (line.length() > 120) {
                    line = "from " + e.getKey() + " import (\n    " + String.join(",\n    ", e.getValue()) + ",\n)";
                }
                target.append(line).append('\n');
            }
            StringBuilder out = new StringBuilder();
            for (StringBuilder group : new StringBuilder[] {std, third, local}) {
                if (group.length() > 0) {
                    if (out.length() > 0) {
                        out.append('\n');
                    }
                    out.append(group);
                }
            }
            return out.toString().stripTrailing();
        }
    }
}
