package ai.caitlyn.codegen.go;

import java.util.TreeSet;
import software.amazon.smithy.codegen.core.ImportContainer;
import software.amazon.smithy.codegen.core.Symbol;
import software.amazon.smithy.codegen.core.SymbolWriter;

/**
 * Writes one Go file of the generated package. Code is written as plain lines (no Smithy formatting
 * expressions, so Go's own {@code $} and {@code %} need no escaping); imports are collected and gofmt
 * lays the file out afterwards.
 */
final class GoWriter extends SymbolWriter<GoWriter, GoWriter.Imports> {

    static final String HEADER = "// Code generated by caitlyn-go-codegen from the Caitlyn Smithy model. DO NOT EDIT.\n\n";

    private final String packageName;

    GoWriter(String packageName) {
        super(new Imports());
        this.packageName = packageName;
        trimTrailingSpaces(true);
    }

    /** Writes text as it is (one or more lines; the writer adds the final newline itself). */
    GoWriter l(String text) {
        if (text.isEmpty()) {
            return this;
        }
        writeWithNoFormatting(text.endsWith("\n") ? text.substring(0, text.length() - 1) : text);
        return this;
    }

    /** Imports a package path. */
    GoWriter imp(String path) {
        getImportContainer().paths.add(path);
        return this;
    }

    @Override
    public String toString() {
        StringBuilder out = new StringBuilder(HEADER).append("package ").append(packageName).append("\n\n");
        if (!getImportContainer().paths.isEmpty()) {
            // Standard library first, then modules (goimports' grouping).
            out.append("import (\n");
            boolean module = false;
            for (boolean std : new boolean[] {true, false}) {
                for (String p : getImportContainer().paths) {
                    if (p.split("/")[0].contains(".") == std) {
                        continue;
                    }
                    if (!std && !module) {
                        out.append('\n');
                        module = true;
                    }
                    out.append('\t').append(Names.str(p)).append('\n');
                }
            }
            out.append(")\n\n");
        }
        return out.append(super.toString()).toString();
    }

    static final class Imports implements ImportContainer {
        final TreeSet<String> paths = new TreeSet<>();

        @Override
        public void importSymbol(Symbol symbol, String alias) {
            if (!symbol.getNamespace().isEmpty()) {
                paths.add(symbol.getNamespace());
            }
        }
    }
}
